package observer;

/**
 * Наблюдател (Observer): всеки обект, който иска да научава за промени в редактора.
 * Примери: панелът с текста, лентата за състоянието, историята на командите.
 */
public interface Observer {

    /**
     * Извиква се от наблюдавания обект след всяка промяна.
     * Наблюдателят сам си взима нужните данни (pull модел), а събитието казва какво се е променило.
     */
    void update(EditorEvent event);
}
